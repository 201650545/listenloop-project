/// **语气词 / 拟声词**表（小学教材范围，2026-10-21）。
///
/// 为什么需要这张表：这些字**短、无语义、声学弱** ⇒ 流式 ASR 很容易把它们
/// **整个吞掉**。真机实测（小米14，回授播放《小蝌蚪找妈妈》）：课文
/// 「小蝌蚪游哇游」被识别成「小蝌蚪游游」——中间的「哇」**消失**。
///
/// 而判定是**逐音节严格对齐** ⇒ 期望比识别多一个音节 ⇒ 中间那位判 missed
/// （红字）⇒ **游标卡住 ⇒ 整句走不完**（孩子明明读对了）。
///
/// 标了这些位之后的语义：
///   · ASR 吐了它 ⇒ 照常配上、判绿；
///   · ASR 吞了它 ⇒ **不判红、不阻塞游标**，全绿判定也把它排除。
///   ⇒ 语气词读没读都不影响「这句读对了没有」。
///
/// ⚠️ **「宁可漏，不可错」**：只收**确定是语气词/拟声词**的单字。
///   拿不准的（可能当实词用的）不放进来 —— 放错了就会放过真读错。
///   例：「哈」可能出现在「哈欠」里 ⇒ 不收；「哒」可能作实词 ⇒ 不收。
library;

/// 小学课文里常见的**语气词**与**拟声词**（单字）。
const Set<String> kFillerChars = {
  // 语气词
  '呀', '吧', '呢', '吗', '啊', '哦', '噢', '嗯', '唉', '呗', '啦', '嘛',
  '咦', '哇', '喔', '哟', '嘿', '呵', '嘻', '嗨',
  // 拟声词（这些字不作实词用）
  '汪', '喵', '咚', '哗', '嘟', '嗷', '轰',
};

/// 这个字是不是「语气词 / 拟声词」（读漏了不算读错）。
bool isFillerChar(String char) => kFillerChars.contains(char);
